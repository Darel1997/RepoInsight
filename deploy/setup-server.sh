#!/usr/bin/env bash
#
# One-shot setup for RepoInsight on a fresh Ubuntu server
# (written for Oracle Cloud Always Free, Ampere A1, Ubuntu 22.04/24.04).
#
# Run from the project folder:
#     bash deploy/setup-server.sh
#
# What it does:
#   1. Installs Docker (if missing)
#   2. Opens ports 80 and 443 in the server's own firewall
#   3. Asks for your domain and free AI keys, generates every secret,
#      and writes .env (readable only by you)
#   4. Builds and starts the app with automatic HTTPS
#
# Safe to run again: it keeps an existing .env unless you ask to replace it.

set -euo pipefail

cd "$(dirname "$0")/.."

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; BOLD='\033[1m'; RESET='\033[0m'
step() { echo -e "\n${BOLD}==> $1${RESET}"; }
ok()   { echo -e "${GREEN}    ✓ $1${RESET}"; }
warn() { echo -e "${YELLOW}    ! $1${RESET}"; }
die()  { echo -e "${RED}    ✗ $1${RESET}"; exit 1; }

[ -f docker-compose.prod.yml ] || die "Run this from the RepoInsight project folder."

# ── 1. Docker ──────────────────────────────────────────────────────
step "Checking Docker"
if ! command -v docker >/dev/null 2>&1; then
    echo "    Installing Docker (takes a minute)..."
    curl -fsSL https://get.docker.com | sudo sh
    sudo usermod -aG docker "$USER" || true
    ok "Docker installed"
else
    ok "Docker already installed"
fi
sudo systemctl enable --now docker >/dev/null 2>&1 || true

# Use sudo for docker until the user logs out and back in (group change).
DOCKER="docker"
if ! docker info >/dev/null 2>&1; then DOCKER="sudo docker"; fi
$DOCKER compose version >/dev/null 2>&1 || die "Docker Compose plugin not found."

# ── 2. Firewall ────────────────────────────────────────────────────
# Oracle's Ubuntu images ship with iptables rules that reject everything
# except SSH. The cloud "security list" must ALSO allow 80/443 — see the guide.
step "Opening ports 80 and 443 on this server"
for port in 80 443; do
    if sudo iptables -C INPUT -p tcp --dport "$port" -j ACCEPT 2>/dev/null; then
        ok "Port $port already open"
    else
        # Insert ABOVE the first REJECT rule, otherwise it never matches.
        reject_line="$(sudo iptables -L INPUT --line-numbers -n | awk '$2=="REJECT"{print $1; exit}')"
        sudo iptables -I INPUT "${reject_line:-1}" -m state --state NEW -p tcp --dport "$port" -j ACCEPT
        ok "Opened port $port"
    fi
done
if command -v netfilter-persistent >/dev/null 2>&1; then
    sudo netfilter-persistent save >/dev/null 2>&1 && ok "Firewall rules saved (survive reboot)"
else
    warn "netfilter-persistent not found; if ports close after a reboot, run this script again."
fi

# ── 3. Configuration (.env) ────────────────────────────────────────
step "Configuring the app"
WRITE_ENV=true
if [ -f .env ]; then
    read -r -p "    A .env file already exists. Replace it? [y/N] " ans
    [[ "$ans" =~ ^[Yy]$ ]] || WRITE_ENV=false
fi

if $WRITE_ENV; then
    echo ""
    echo "    Your domain must already point at this server's public IP"
    echo "    (e.g. myname-repoinsight.duckdns.org — see the guide)."
    read -r -p "    Domain (no https://): " DOMAIN
    DOMAIN="${DOMAIN#http://}"; DOMAIN="${DOMAIN#https://}"; DOMAIN="${DOMAIN%%/*}"
    [ -n "$DOMAIN" ] || die "A domain is required for HTTPS."

    echo ""
    echo "    Free AI keys (set at least one; both is best):"
    echo "      Gemini: https://aistudio.google.com/apikey"
    echo "      Groq:   https://console.groq.com/keys"
    read -r -p "    Gemini API key: " GEMINI_API_KEY
    read -r -p "    Groq API key:   " GROQ_API_KEY
    [ -n "$GEMINI_API_KEY$GROQ_API_KEY" ] || die "At least one AI key is required."

    echo ""
    echo "    GitHub sign-in is optional (press Enter to skip). Without it, visitors"
    echo "    register with email and can analyze any public repository."
    read -r -p "    GitHub OAuth Client ID: " GITHUB_CLIENT_ID
    GITHUB_CLIENT_SECRET=""
    if [ -n "$GITHUB_CLIENT_ID" ]; then
        read -r -p "    GitHub OAuth Client Secret: " GITHUB_CLIENT_SECRET
    fi

    umask 077
    cat > .env <<EOF
# Generated by deploy/setup-server.sh on $(date -u +%Y-%m-%d). Keep this file private.
APP_ENV=production
DEBUG=false
DOMAIN=${DOMAIN}

# Secrets (randomly generated)
POSTGRES_PASSWORD=$(openssl rand -hex 24)
JWT_SECRET=$(openssl rand -hex 32)
JWT_ALGORITHM=HS256
JWT_EXPIRE_MINUTES=1440
ENCRYPTION_KEY=$(openssl rand -base64 32)

# AI (free tiers)
AI_PROVIDER_ORDER=gemini,groq
GEMINI_API_KEY=${GEMINI_API_KEY}
GROQ_API_KEY=${GROQ_API_KEY}
ANTHROPIC_API_KEY=not-set
OPENAI_API_KEY=not-set

# GitHub OAuth (callback URL: https://${DOMAIN}/auth/github/callback)
GITHUB_CLIENT_ID=${GITHUB_CLIENT_ID}
GITHUB_CLIENT_SECRET=${GITHUB_CLIENT_SECRET}

RATE_LIMIT_PER_MINUTE=60
EOF
    umask 022
    ok ".env written (only you can read it)"
else
    ok "Keeping existing .env"
fi

DOMAIN="$(grep -E '^DOMAIN=' .env | cut -d= -f2-)"
[ -n "$DOMAIN" ] || die "DOMAIN is missing from .env."

# ── DNS sanity check ───────────────────────────────────────────────
step "Checking that $DOMAIN points at this server"
PUBLIC_IP="$(curl -fsS -4 --max-time 5 https://ifconfig.me 2>/dev/null || true)"
DNS_IP="$(getent ahostsv4 "$DOMAIN" 2>/dev/null | awk 'NR==1{print $1}' || true)"
if [ -n "$PUBLIC_IP" ] && [ "$PUBLIC_IP" = "$DNS_IP" ]; then
    ok "$DOMAIN → $PUBLIC_IP"
else
    warn "$DOMAIN resolves to '${DNS_IP:-nothing}', but this server's IP is '${PUBLIC_IP:-unknown}'."
    warn "HTTPS will fail until they match. Fix the DNS record, then re-run this script."
    read -r -p "    Continue anyway? [y/N] " ans
    [[ "$ans" =~ ^[Yy]$ ]] || exit 1
fi

# ── 4. Build and start ─────────────────────────────────────────────
step "Building and starting RepoInsight (first build takes 10–20 minutes)"
$DOCKER compose -f docker-compose.prod.yml up -d --build

step "Waiting for the app to come up"
for _ in $(seq 1 60); do
    if curl -fsS --max-time 5 "https://${DOMAIN}/health" >/dev/null 2>&1; then
        ok "RepoInsight is live"
        echo ""
        echo -e "    ${BOLD}https://${DOMAIN}${RESET}"
        echo ""
        echo "    Put that link on your portfolio."
        echo "    Logs:    $DOCKER compose -f docker-compose.prod.yml logs -f --tail 50"
        echo "    Status:  $DOCKER compose -f docker-compose.prod.yml ps"
        exit 0
    fi
    sleep 10
done

warn "The site didn't answer over HTTPS within 10 minutes."
echo "    Check:  $DOCKER compose -f docker-compose.prod.yml ps"
echo "            $DOCKER compose -f docker-compose.prod.yml logs caddy --tail 30"
echo "    Most common causes: ports 80/443 not open in the Oracle security list,"
echo "    or the domain not pointing at this server yet."
exit 1
